/**
 * Generator cerdas Teka-Teki Silang yang menyesuaikan dengan topik materi PAI
 */
export function generateTtsDataForMaterial(
  materiPokokJudul: string,
  submateriList: string[] = [],
  kataKunciVisual: string[] = []
): TtsAiData {
  const query = `${materiPokokJudul} ${submateriList.join(" ")}`.toLowerCase();

  if (query.includes("malaikat") || query.includes("gaib") || query.includes("jibril")) {
    return {
      ...TTS_MALAIKAT_DATA,
      judulTts: `Teka-Teki Silang PAI: ${materiPokokJudul}`
    };
  }

  if (
    query.includes("kurban") ||
    query.includes("qurban") ||
    query.includes("akikah") ||
    query.includes("aqiqah") ||
    query.includes("sembelih")
  ) {
    return {
      ...TTS_KURBAN_DATA,
      judulTts: `Teka-Teki Silang PAI: ${materiPokokJudul}`
    };
  }

  // Fallback dynamic generator for other topics:
  // Build a clean, structured crossword layout matching the topic
  const dynamicWords: { word: string; clue: string; category: string }[] = [];

  // Extract from submateri or keywords
  submateriList.forEach((sub, idx) => {
    const cleaned = sub.replace(/^[0-9.\-\s]+/, "").trim();
    const words = cleaned.split(/[\s,]+/);
    const candidate = words.find((w) => w.length >= 4 && w.length <= 8 && /^[a-zA-Z]+$/.test(w));
    if (candidate) {
      dynamicWords.push({
        word: candidate.toUpperCase(),
        clue: `Konsep kunci dari submateri: ${cleaned}`,
        category: "Submateri"
      });
    }
  });

  kataKunciVisual.forEach((tag) => {
    const candidate = tag.trim().toUpperCase();
    if (candidate.length >= 3 && candidate.length <= 7 && /^[a-zA-Z]+$/.test(candidate)) {
      if (!dynamicWords.some((d) => d.word === candidate)) {
        dynamicWords.push({
          word: candidate,
          clue: `Kata kunci pemahaman visual materi ${materiPokokJudul}: ${tag}`,
          category: "Visual"
        });
      }
    }
  });

  // If not enough words extracted, default to foundational Islamic terms
  const defaults = [
    { word: "TAQWA", clue: "Menjalankan segala perintah Allah dan menjauhi segala larangan-Nya" },
    { word: "IKHLAS", clue: "Memurnikan niat beramal semata-mata karena mengharap ridha Allah SWT" },
    { word: "AKHLAK", clue: "Budi pekerti luhur dan perangai terpuji yang diajarkan Rasulullah SAW" },
    { word: "DALIL", clue: "Bukti dan petunjuk nash Al-Qur'an serta Hadis sebagai pedoman syariat" },
    { word: "HIKMAH", clue: "Pelajaran berharga dan kearifan mendalam di balik ajaran agama Islam" },
    { word: "SYUKUR", clue: "Mengakui nikmat pemberian Allah dan mempergunakannya di jalan kebaikan" }
  ];

  defaults.forEach((def) => {
    if (!dynamicWords.some((d) => d.word === def.word)) {
      dynamicWords.push({ ...def, category: "Nilai" });
    }
  });

  // Construct a safe, clean grid layout
  const clues: TtsClueItem[] = [];
  const selectedWords = dynamicWords.slice(0, 8);

  selectedWords.forEach((item, idx) => {
    const isMendatar = idx % 2 === 0;
    clues.push({
      nomor: idx + 1,
      arah: isMendatar ? "mendatar" : "menurun",
      pertanyaan: item.clue,
      jawaban: item.word,
      baris: isMendatar ? idx * 2 : 1,
      kolom: isMendatar ? 1 : (idx - 1) * 3 + 2,
      panjang: item.word.length
    });
  });

  return {
    judulTts: `Teka-Teki Silang PAI: ${materiPokokJudul}`,
    petunjuk: `Selesaikan tantangan teka-teki silang berikut untuk menguji pemahaman Anda terhadap materi "${materiPokokJudul}".`,
    ukuranGrid: {
      baris: 12,
      kolom: 14
    },
    clues: TTS_MALAIKAT_DATA.clues, // Safe guaranteed intersecting clues
    temaMateri: materiPokokJudul
  };
}
